import { readFile, writeFile } from 'node:fs/promises';
const schema = await readFile(new URL('../src/lib/clientRegistration.js', import.meta.url), 'utf8');
const handler = await readFile(new URL('../google-apps-script/alta-clientes-handler.js.txt', import.meta.url), 'utf8');
const mail = await readFile(new URL('../google-apps-script/alta-clientes-mail.js.txt', import.meta.url), 'utf8');
const output = '// Generated by npm run alta:script. Edit shared schema / handler / mail, then regenerate.\n' + schema.replace(/^export /gm, '') + '\n' + handler + '\n' + mail;
await writeFile(new URL('../google-apps-script/alta-clientes.gs', import.meta.url), output);
